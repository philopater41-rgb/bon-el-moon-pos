import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { prisma } from '../src/lib/db';
import { POST as sync } from '../src/app/api/sync/route';
import { POST as refund } from '../src/app/api/returns/route';
import { GET as active } from '../src/app/api/shifts/active/route';
import { POST as close } from '../src/app/api/shifts/close/route';
import { GET as analytics } from '../src/app/api/admin-analytics/route';
import { GET as report } from '../src/app/api/reports/detailed/route';
import { GET as ledger } from '../src/app/api/sales-ledger/route';
import { cairoDateKey } from '../src/lib/cairo-date';
import { PATCH as payInvoice, POST as createInvoice } from '../src/app/api/purchases/route';
import { GET as listCustomers } from '../src/app/api/customers/route';
import { GET as listInventory, DELETE as deleteMaterial } from '../src/app/api/inventory/route';
import { POST as createItem, PUT as updateItem } from '../src/app/api/items/route';
import { POST as addExpense, DELETE as removeExpense } from '../src/app/api/shifts/expenses/route';
import { GET as listRecipes, POST as saveRecipe } from '../src/app/api/recipes/route';

if (!process.env.DATABASE_URL?.includes('bon-isolated-regression')) throw new Error('Use only the isolated regression database');
const req = (body: unknown) => new Request('http://localhost/test', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
async function main() {
  await prisma.shift.updateMany({ where: { closedAt: null }, data: { closedAt: new Date() } });
  const user = await prisma.user.findFirstOrThrow();
  const item = await prisma.item.findFirstOrThrow();
  const shift = await prisma.shift.create({ data: { userId: user.id, floatCash: 100, cashierName: 'Test' } });
  const customer = await prisma.customer.create({ data: { name: 'Regression customer' } });
  const orderId = randomUUID();
  const order = { id: orderId, customerId: customer.id, shiftId: shift.id, orderType: 'TAKEAWAY', paymentMethod: 'VISA', status: 'COMPLETED', subtotal: 100, discount: 0, tax: 0, total: 100, createdAt: new Date().toISOString(), items: [{ id: randomUUID(), itemId: item.id, qty: 2, unitPrice: 50, totalPrice: 100 }] };
  let data = await (await sync(req({ orders: [order] }))).json();
  assert.deepEqual(data.syncedIds, [orderId]);
  data = await (await sync(req({ orders: [{ ...order, id: randomUUID(), shiftId: 'missing' }] }))).json();
  assert.equal(data.syncedIds.length, 0); assert.equal(data.errors.length, 1);
  data = await (await sync(req({ orders: [{ ...order, id: randomUUID(), items: [{ ...order.items[0], id: randomUUID(), itemId: 'missing' }] }] }))).json();
  assert.equal(data.syncedIds.length, 0); assert.equal(data.errors.length, 1);
  const invalid = { orderId, shiftId: shift.id, reason: 'test', paymentMethod: 'CASH', restockItems: false };
  assert.equal((await refund(req({ ...invalid, refundAmount: 101 }))).status, 400);
  assert.equal((await refund(req({ ...invalid, refundAmount: 50, items: [{ itemId: item.id, quantity: 3, refundPrice: 50 }] }))).status, 400);
  assert.equal((await refund(req({ ...invalid, refundAmount: 50, items: [{ itemId: item.id, quantity: 1, refundPrice: 50 }] }))).status, 200);
  const customers = await (await listCustomers()).json();
  assert.equal(customers.customers.find((c: { id: string }) => c.id === customer.id).totalSpent, 50);
  assert.equal((await refund(req({ ...invalid, refundAmount: 60 }))).status, 400);
  assert.equal((await refund(req({ ...invalid, refundAmount: 50, items: [{ itemId: item.id, quantity: 2, refundPrice: 50 }] }))).status, 400);
  data = await (await active()).json(); assert.equal(data.activeShift.expectedCash, 50); assert.equal(data.activeShift.expectedVisa, 100);
  data = await (await close(req({ shiftId: shift.id, closedCash: 50, closedVisa: 100 }))).json(); assert.equal(data.shift.expectedCash, 50); assert.equal(data.shift.expectedVisa, 100);
  assert.equal((await addExpense(req({ type: 'PAYOUT', amount: 10, reason: 'No open shift' }))).status, 400);
  assert.equal((await addExpense(req({ shiftId: shift.id, type: 'PAYOUT', amount: 10, reason: 'Closed shift' }))).status, 400);
  const cashShift = await prisma.shift.create({ data: { userId: user.id, floatCash: 1000, cashierName: 'Test cash-out' } });
  assert.equal((await addExpense(req({ shiftId: cashShift.id, type: 'PAYOUT', amount: -5, reason: 'invalid' }))).status, 400);
  assert.equal((await addExpense(req({ shiftId: cashShift.id, type: 'PAYOUT', amount: 5, reason: '   ' }))).status, 400);
  const expenseResult = await addExpense(req({ shiftId: cashShift.id, type: 'PAYOUT', amount: 5, reason: 'valid' }));
  assert.equal(expenseResult.status, 200);
  const expense = (await expenseResult.json()).transaction;
  assert.equal((await removeExpense(new Request(`http://localhost/api/shifts/expenses?id=${expense.id}`, { method: 'DELETE' }))).status, 200);
  const closedExpense = await prisma.cashTransaction.create({ data: { shiftId: shift.id, type: 'PAYOUT', amount: 5, reason: 'history' } });
  assert.equal((await removeExpense(new Request(`http://localhost/api/shifts/expenses?id=${closedExpense.id}`, { method: 'DELETE' }))).status, 409);
  const day = cairoDateKey(new Date());
  const reportRequest = () => new Request(`http://localhost/api/reports/detailed?startDate=${day}&endDate=${day}`);
  const ledgerRequest = () => new Request(`http://localhost/api/sales-ledger?date=${day}`);
  const beforeAnalytics = await (await analytics()).json();
  const beforeReport = await (await report(reportRequest())).json();
  const beforeLedger = await (await ledger(ledgerRequest())).json();
  const cashId = randomUUID();
  data = await (await sync(req({ orders: [{ id: cashId, shiftId: cashShift.id, orderType: 'TAKEAWAY', paymentMethod: 'CASH_OUT', cashOutAmount: 400, cashOutFee: 10, status: 'COMPLETED', subtotal: 410, discount: 0, tax: 0, total: 410, createdAt: new Date().toISOString(), items: [] }] }))).json();
  assert.deepEqual(data.syncedIds, [cashId]);
  const afterAnalytics = await (await analytics()).json();
  const afterReport = await (await report(reportRequest())).json();
  const afterLedger = await (await ledger(ledgerRequest())).json();
  assert.equal(afterAnalytics.kpis.todaySales - beforeAnalytics.kpis.todaySales, 10);
  assert.equal(afterReport.summary.totalNetRevenue - beforeReport.summary.totalNetRevenue, 10);
  assert.equal(afterLedger.summary.totalNet - beforeLedger.summary.totalNet, 10);
  data = await (await active()).json();
  assert.equal(data.activeShift.expectedCash, 600); assert.equal(data.activeShift.expectedVisa, 410);
  for (const [method, amount] of [['INSTAPAY', 22], ['VODAFONE_CASH', 33]] as const) {
    const id = randomUUID();
    const paymentOrder = { ...order, id, shiftId: cashShift.id, paymentMethod: method, subtotal: amount, total: amount, items: [{ id: randomUUID(), itemId: item.id, qty: 1, unitPrice: amount, totalPrice: amount }] };
    const response = await (await sync(req({ orders: [paymentOrder] }))).json();
    assert.deepEqual(response.syncedIds, [id]);
  }
  data = await (await active()).json();
  assert.equal(data.activeShift.expectedInstaPay, 22); assert.equal(data.activeShift.expectedVodafoneCash, 33);
  const material = await prisma.rawMaterial.findFirstOrThrow();
  const initialStock = material.stockQty;
  assert.equal((await createInvoice(req({ items: [{ rawMaterialId: material.id, itemName: material.name, quantity: -1, totalPrice: 10 }] }))).status, 400);
  assert.equal((await createInvoice(req({ items: [{ rawMaterialId: material.id, itemName: material.name, quantity: 1, totalPrice: 10 }], paidAmount: 11 }))).status, 400);
  assert.equal((await prisma.rawMaterial.findUniqueOrThrow({ where: { id: material.id } })).stockQty, initialStock);
  const invoice = await prisma.purchaseInvoice.create({ data: { totalAmount: 100, paidAmount: 20, remainingAmount: 80 } });
  assert.equal((await payInvoice(req({ invoiceId: invoice.id, paymentAmount: 81 }))).status, 400);
  assert.equal((await payInvoice(req({ invoiceId: invoice.id, paymentAmount: 30 }))).status, 200);
  const paidInvoice = await prisma.purchaseInvoice.findUniqueOrThrow({ where: { id: invoice.id } });
  assert.equal(paidInvoice.paidAmount, 50); assert.equal(paidInvoice.remainingAmount, 50);
  const safeMaterial = await prisma.rawMaterial.create({ data: { name: `Regression material ${randomUUID()}`, stockQty: 20, purchaseUnit: 'kg', deductUnit: 'g' } });
  const newItemName = `Failed create ${randomUUID()}`;
  const newCategoryName = `Failed category ${randomUUID()}`;
  assert.notEqual((await createItem(req({ name: newItemName, price: 20, categoryName: newCategoryName, recipe: [{ rawMaterialId: 'missing-material', quantity: 1 }] }))).status, 201);
  assert.equal(await prisma.item.count({ where: { name: newItemName } }), 0);
  assert.equal(await prisma.category.count({ where: { name: newCategoryName } }), 0);
  const testItem = await prisma.item.create({ data: { name: `Recipe regression ${randomUUID()}`, price: 20, categoryId: item.categoryId, recipe: { create: { rawMaterialId: safeMaterial.id, quantity: 2 } } } });
  const failedEdit = await updateItem(req({ id: testItem.id, name: 'Changed name', price: 25, recipe: [{ rawMaterialId: 'missing-material', quantity: 2 }] }));
  assert.notEqual(failedEdit.status, 200);
  const unchangedItem = await prisma.item.findUniqueOrThrow({ where: { id: testItem.id }, include: { recipe: true } });
  assert.equal(unchangedItem.name, testItem.name); assert.equal(unchangedItem.price, 20);
  assert.equal(unchangedItem.recipe.length, 1); assert.equal(unchangedItem.recipe[0].rawMaterialId, safeMaterial.id);
  assert.notEqual((await saveRecipe(req({ itemId: testItem.id, ingredients: [{ rawMaterialId: 'missing-material', quantity: 2 }] }))).status, 200);
  assert.equal((await prisma.recipe.findMany({ where: { itemId: testItem.id } })).length, 1);
  assert.equal((await saveRecipe(req({ itemId: testItem.id, ingredients: [{ rawMaterialId: safeMaterial.id, quantity: 3 }] }))).status, 200);
  assert.equal((await prisma.recipe.findFirstOrThrow({ where: { itemId: testItem.id } })).quantity, 3);
  assert.equal((await updateItem(req({ id: testItem.id, name: testItem.name, price: 25, recipe: [{ rawMaterialId: safeMaterial.id, quantity: 4 }] }))).status, 200);
  assert.equal((await prisma.recipe.findFirstOrThrow({ where: { itemId: testItem.id } })).quantity, 4);
  await prisma.recipe.deleteMany({ where: { itemId: testItem.id } });
  const oldLog = await prisma.wastageLog.create({ data: { rawMaterialId: safeMaterial.id, quantity: 1, reason: 'test' } });
  const oldRestock = await prisma.restockLog.create({ data: { rawMaterialId: safeMaterial.id, quantity: 1, amount: 10 } });
  await prisma.recipe.create({ data: { itemId: item.id, rawMaterialId: safeMaterial.id, quantity: 1 } });
  const deleteReq = () => new Request(`http://localhost/api/inventory?id=${safeMaterial.id}`, { method: 'DELETE' });
  assert.equal((await deleteMaterial(deleteReq())).status, 409);
  await prisma.recipe.deleteMany({ where: { rawMaterialId: safeMaterial.id } });
  assert.equal((await deleteMaterial(deleteReq())).status, 200);
  assert.equal((await prisma.rawMaterial.findUniqueOrThrow({ where: { id: safeMaterial.id } })).isActive, false);
  assert.ok(await prisma.wastageLog.findUnique({ where: { id: oldLog.id } }));
  assert.ok(await prisma.restockLog.findUnique({ where: { id: oldRestock.id } }));
  const inventory = await (await listInventory()).json();
  assert.equal(inventory.rawMaterials.some((m: { id: string }) => m.id === safeMaterial.id), false);
  const recipes = await (await listRecipes()).json();
  assert.equal(recipes.rawMaterials.some((m: { id: string }) => m.id === safeMaterial.id), false);
  const midnightId = randomUUID();
  const midnightOrder = { ...order, id: midnightId, shiftId: cashShift.id, customerId: null, createdAt: '2026-01-04T22:30:00.000Z', items: [{ id: randomUUID(), itemId: item.id, qty: 1, unitPrice: 100, totalPrice: 100 }] };
  assert.deepEqual((await (await sync(req({ orders: [midnightOrder] }))).json()).syncedIds, [midnightId]);
  const midnightReport = await (await report(new Request('http://localhost/api/reports/detailed?startDate=2026-01-05&endDate=2026-01-05'))).json();
  assert.ok(midnightReport.dailyTrends.some((d: { date: string }) => d.date === '2026-01-05'));
  assert.ok(!midnightReport.dailyTrends.some((d: { date: string }) => d.date === '2026-01-04'));
  const manualCostItem = await prisma.item.create({ data: { name: `Manual cost ${randomUUID()}`, categoryId: item.categoryId, price: 100, cost: 20 } });
  const costOrderId = randomUUID();
  const costOrder = { ...order, id: costOrderId, shiftId: cashShift.id, customerId: null, subtotal: 100, discount: 10, total: 90, createdAt: '2026-01-06T10:00:00.000Z', items: [{ id: randomUUID(), itemId: manualCostItem.id, qty: 1, unitPrice: 100, totalPrice: 100 }] };
  assert.deepEqual((await (await sync(req({ orders: [costOrder] }))).json()).syncedIds, [costOrderId]);
  const costReport = await (await report(new Request('http://localhost/api/reports/detailed?startDate=2026-01-06&endDate=2026-01-06'))).json();
  assert.equal(costReport.summary.totalCOGS, 20);
  assert.equal(costReport.summary.overallNetProfit, 70);
  assert.equal(costReport.dailyTrends[0].profit, 70);
  const cashOnlyReport = await (await report(new Request(`http://localhost/api/reports/detailed?startDate=${day}&endDate=${day}&paymentMethod=CASH_OUT`))).json();
  assert.equal(cashOnlyReport.summary.totalNetRevenue, 10);
  assert.equal(cashOnlyReport.dailyTrends[0].profit, 10);
  console.log('Regression checks passed: invalid references, refund limits, quantities, payment method and shift reconciliation.');
}
main().finally(() => prisma.$disconnect()).catch(err => { console.error(err); process.exitCode = 1; });
